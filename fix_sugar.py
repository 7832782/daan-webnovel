import pathlib
base = pathlib.Path("D:/desktop/答案网文版/正文/第四卷_退潮")

def rep(name, pairs):
    p = base / name
    t = p.read_text(encoding="utf-8")
    orig = t
    for old, new in pairs:
        if old in t:
            t = t.replace(old, new)
        else:
            print(f"[{name}] NOT FOUND: {old[:30]}")
    if t != orig:
        p.write_text(t, encoding="utf-8")
        print(f"[{name}] updated {len(pairs)} rules")
    else:
        print(f"[{name}] no change")

